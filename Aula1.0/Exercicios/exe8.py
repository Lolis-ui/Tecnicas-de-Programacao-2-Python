#Soma seguido de potenciação

x = float(input("Digite um número: "))
y = float(input("Digite um número: "))
z = float(input("Digite um número: "))

soma = (x + y + z)
print(f"O valor da soma dos números {x},{y},{z} é igual a: {soma}")

potencia = (soma **2)
print(f"O número {soma}² é igual a: {potencia}")