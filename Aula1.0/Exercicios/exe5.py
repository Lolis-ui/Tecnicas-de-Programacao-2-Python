#As quatro operações
num1 = float(input("Digite um número: "))
num2 = float(input("Digite um  outro número: "))

input("Adição")
adicao = num1 + num2
print(f"A adição dos numeros {num1} + {num2} é igual a: {adicao}")

input("Subtação")
subtracao = num1 + num2
print(f"A subtração dos numeros {num1} - {num2} é igual a: {subtracao}")

input("Multiplicação")
multiplicacao = num1 + num2
print(f"A multiplicação dos numeros {num1} * {num2} é igual a: {multiplicacao}")

input("Divisão")
divisao = num1 + num2
print(f"A divisão dos numeros {num1} / {num2} é igual a: {divisao:.2f}")



